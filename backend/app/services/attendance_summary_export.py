"""The Attendance Summary as a downloadable Excel file - the exact same numbers as the screen.

Builds its rows from `get_attendance_summary` (the same call the page itself makes), so the file
can never show a different number than what the Accountant or Founder already saw on screen.
"""

from io import BytesIO

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet
from sqlalchemy.ext.asyncio import AsyncSession

from app.schemas.payroll import AttendanceSummaryOut
from app.services.payroll_attendance_service import get_attendance_summary

MONTH_NAMES = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]

HEADER_FILL = PatternFill("solid", fgColor="1E2761")
HEADER_FONT = Font(color="FFFFFF", bold=True)
TITLE_FONT = Font(bold=True, size=14, color="1E2761")
NOTE_FONT = Font(italic=True, size=9, color="6B7280")

COLUMNS = [
    ("Employee code", "employee_code", 14, None),
    ("Employee name", "employee_name", 22, None),
    ("Total days", "total_days", 11, "0"),
    ("Working days", "working_days", 12, "0"),
    ("Present", "present", 9, "0"),
    ("Late", "late", 8, "0"),
    ("Half day", "half_day", 9, "0"),
    ("Paid leave", "paid_leave", 10, "0"),
    ("Unpaid leave", "unpaid_leave", 12, "0"),
    ("Half-day leave", "half_leave", 12, "0"),
    ("Absent", "absent", 9, "0"),
    ("Days off", "days_off", 9, "0"),
    ("Payable days", "payable_days", 12, "0.0"),
    ("Days cut", "cut_days", 10, "0.0"),
    ("Monthly salary (Rs.)", "monthly_salary", 16, "#,##0.00"),
    ("Pay by attendance (Rs.)", "pay_for_month", 18, "#,##0.00"),
    ("On payslip (Rs.)", "payslip_amount", 15, "#,##0.00"),
    ("Payslip status", "payslip_status", 13, None),
    ("Payslip paid date", "payslip_paid_date", 15, "dd mmm yyyy"),
    ("Difference (Rs.)", "difference", 14, "#,##0.00"),
    ("Missed check-outs", "missed_check_outs", 14, "0"),
    ("Pending leave requests", "pending_leave_requests", 18, "0"),
]


def _column_of(field: str) -> int:
    """1-based column number of a field, so totals never point at the wrong column when columns are added."""
    return [f for _, f, _, _ in COLUMNS].index(field) + 1


def _write_header(sheet: Worksheet, data: AttendanceSummaryOut, generated_note: str) -> int:
    sheet.merge_cells("A1:F1")
    title_cell = sheet["A1"]
    title_cell.value = f"Attendance Summary - {MONTH_NAMES[data.month - 1]} {data.year}"
    title_cell.font = TITLE_FONT

    sheet["A2"] = generated_note
    sheet["A2"].font = NOTE_FONT

    row = 4
    for col_index, (label, _, width, number_format) in enumerate(COLUMNS, start=1):
        cell = sheet.cell(row=row, column=col_index, value=label)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", wrap_text=True)
        sheet.column_dimensions[get_column_letter(col_index)].width = width
    sheet.freeze_panes = f"A{row + 1}"
    return row + 1


def build_attendance_summary_workbook(data: AttendanceSummaryOut, generated_by: str, generated_at: str) -> bytes:
    """One row per employee, in the same order the screen shows them (issues first)."""
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = f"{MONTH_NAMES[data.month - 1][:3]} {data.year}"

    first_data_row = _write_header(sheet, data, f"Generated by {generated_by} on {generated_at}")

    for offset, item in enumerate(data.items):
        row = first_data_row + offset
        values = item.model_dump()
        for col_index, (_, field, _, number_format) in enumerate(COLUMNS, start=1):
            value = values.get(field)
            if field == "payslip_status" and value is not None:
                value = value.value if hasattr(value, "value") else str(value)
            cell = sheet.cell(row=row, column=col_index, value=value)
            if number_format:
                cell.number_format = number_format
            if field in ("cut_days", "difference") and isinstance(value, (int, float)) and value:
                cell.font = Font(color="B91C1C" if value > 0 or field == "cut_days" else "1E2761")

    last_row = first_data_row + len(data.items) - 1
    if data.items:
        totals_row = last_row + 2
        sheet.cell(row=totals_row, column=1, value="Totals").font = Font(bold=True)
        sheet.cell(row=totals_row, column=_column_of("monthly_salary"), value=data.total_monthly_salary).number_format = "#,##0.00"
        sheet.cell(row=totals_row, column=_column_of("monthly_salary")).font = Font(bold=True)
        if data.total_pay is not None:
            sheet.cell(row=totals_row, column=_column_of("pay_for_month"), value=data.total_pay).number_format = "#,##0.00"
            sheet.cell(row=totals_row, column=_column_of("pay_for_month")).font = Font(bold=True)
        if data.total_on_payslips is not None:
            sheet.cell(row=totals_row, column=_column_of("payslip_amount"), value=data.total_on_payslips).number_format = "#,##0.00"
            sheet.cell(row=totals_row, column=_column_of("payslip_amount")).font = Font(bold=True)
        if data.total_difference is not None:
            sheet.cell(row=totals_row, column=_column_of("difference"), value=data.total_difference).number_format = "#,##0.00"
            sheet.cell(row=totals_row, column=_column_of("difference")).font = Font(bold=True)
    else:
        sheet.cell(row=first_data_row, column=1, value="No one has a salary structure set for this month.")

    checklist_row = (last_row if data.items else first_data_row) + 4
    sheet.cell(row=checklist_row, column=1, value="Before you pay (at the time this file was made):").font = Font(bold=True)
    checklist_lines = [
        f"Missed check-outs in {MONTH_NAMES[data.month - 1]} {data.year}: {data.checklist.missed_check_outs}",
        f"Pending leave requests: {data.checklist.pending_leave_requests}",
        f"Active employees with no salary set: {data.checklist.employees_without_salary}",
        f"Total absent days: {data.checklist.absent_days}",
    ]
    for offset, line in enumerate(checklist_lines, start=1):
        sheet.cell(row=checklist_row + offset, column=1, value=line)

    buffer = BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


async def export_attendance_summary(
    session: AsyncSession, year: int, month: int, generated_by: str, generated_at: str
) -> bytes:
    """Fetches the same data the Attendance Summary page shows, then renders it as an .xlsx file."""
    data = await get_attendance_summary(session, year, month)
    return build_attendance_summary_workbook(data, generated_by, generated_at)
